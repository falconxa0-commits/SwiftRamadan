/* ──────────────────────────────────────────────────────────────────
   /api/diary — Ramadan Diary
   GET  returns diary entries
   POST creates a new diary entry
   ────────────────────────────────────────────────────────────────── */

type Mood = 'blessed' | 'happy' | 'neutral' | 'tired' | 'grateful';

interface DiaryEntryShape {
  id: string;
  date: string;
  text: string;
  mood: Mood;
  orderId?: string;
  autoGenerated?: boolean;
  tags?: string[];
}

